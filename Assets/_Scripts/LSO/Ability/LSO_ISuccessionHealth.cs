namespace _Scripts.LSO.Ability
{
    /// <summary>
    /// 계승으로 넘길 체력을 특성이 직접 정한다.
    ///
    /// ── 왜 필요한가 ───────────────────────────────────────────
    /// 계승은 죽는 기물의 <b>최대 체력</b>을 보고 넘길 양을 정한다.
    /// 그런데 최대 체력이 "얼마나 단단한가"를 뜻하지 않는 기물이 있다.
    ///
    /// 개복치가 그렇다. 체력이 999지만 그것은 맞아도 안 죽는다는 표현이고,
    /// 실제로 안 죽게 만드는 것은 허약(LSO_Frail)이 피해를 0으로 만들기 때문이다.
    /// 그 999를 그대로 계승하면 물려받은 기물이 체력 +333을 받는다.
    ///
    /// 그래서 "계승에는 얼마로 치는가"를 특성이 스스로 말하게 한다.
    /// ─────────────────────────────────────────────────────────
    ///
    /// 계승하는 쪽은 어떤 특성이 이걸 구현했는지 몰라야 한다.
    /// 특성 이름을 계승 코드가 직접 알면, 비슷한 기물이 하나 늘 때마다
    /// 계승 쪽을 같이 고쳐야 한다.
    ///
    /// 실제 체력은 건드리지 않는다. 화면에 보이는 숫자도 그대로다 —
    /// <b>계승 계산에서만</b> 이 값을 대신 쓴다.
    /// </summary>
    public interface LSO_ISuccessionHealth
    {
        /// <summary>
        /// 계승 계산에 쓸 체력. 최대 체력 대신 이 값이 들어간다.
        ///
        /// 넘길 양은 계승 쪽 공식이 정한다 — 여기서 내놓는 것은 "기준이 될 체력"이지
        /// "물려줄 양"이 아니다.
        /// </summary>
        int SuccessionHealth { get; }
    }
}
