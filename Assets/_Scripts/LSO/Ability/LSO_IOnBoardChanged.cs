namespace _Scripts.LSO.Ability
{
    /// <summary>
    /// 판 위의 기물 배치가 바뀔 때마다 알림을 받는 특성.
    ///
    /// ── 왜 필요한가 ───────────────────────────────────────────
    /// 무리 사냥처럼 **주변을 보는** 특성은 발동하는 순간이 따로 없다.
    /// 옆에 누가 서 있는 동안 계속 켜져 있는 상태다.
    ///
    /// 그런데 공격력을 물어볼 때(IStatModifier)는 초당 수십 번 불리므로
    /// 거기서 연출을 내면 이펙트가 끊임없이 터진다.
    ///
    /// 판이 바뀌는 순간은 드물고(놓기·이동·죽음) 그때만 다시 세면 되므로,
    /// "언제 달라졌는지"를 알 자리를 따로 둔다.
    /// ─────────────────────────────────────────────────────────
    ///
    /// 등록·해제는 LSO_AbilityWiring 이 맡는다. 특성이 직접 구독하지 않는다 —
    /// 직접 구독하면 기물이 죽은 뒤에도 보드가 특성을 붙잡고 있게 된다.
    /// </summary>
    public interface LSO_IOnBoardChanged
    {
        /// <summary>판 위의 무언가가 놓이거나 옮겨지거나 사라졌다.</summary>
        void OnBoardChanged();
    }
}
