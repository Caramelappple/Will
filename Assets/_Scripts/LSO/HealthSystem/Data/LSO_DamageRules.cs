namespace _Scripts.LSO.HealthSystem.Data
{
    /// <summary>
    /// 피해를 두고 **특성이 물어보는 규칙**을 모아둔 곳.
    ///
    /// ── 왜 한 군데여야 하나 ───────────────────────────────────
    /// "상어왕 영역 공격은 옹골참으로 못 버틴다"를 옹골참과 허약에 각각 적으면,
    /// 같은 규칙이 두 벌 생긴다. 나중에 같은 성질의 공격이 하나 더 늘면 방어
    /// 특성을 전부 찾아다니며 고쳐야 하고, 그러다 하나를 빠뜨리면 그 특성만
    /// 조용히 막아낸다. 어느 쪽이 맞는지 정할 방법이 없어진다.
    ///
    /// 그래서 "무엇이 방어를 뚫는가"를 정하는 주체를 여기 하나로 둔다.
    /// 방어 특성은 판단하지 않고 물어보기만 한다.
    /// ─────────────────────────────────────────────────────────
    ///
    /// 새로 뚫는 공격이 생기면 아래 목록에 한 줄 더하면 된다. 특성은 손대지 않는다.
    /// </summary>
    public static class LSO_DamageRules
    {
        /// <summary>
        /// 이 피해를 특성으로 막을 수 있는지.
        ///
        /// true 면 방어 계열 특성(옹골참·허약·저주 면역 등)은 **비켜서야 한다.**
        /// 들어온 피해를 그대로 통과시키라는 뜻이며, 발동한 것으로 기록하지도 않는다.
        ///
        /// 피해량 자체를 바꾸지는 않는다. 체력이 많은 기물은 여전히 버틴다 —
        /// 막을 수 없다는 것과 반드시 죽는다는 것은 다르다.
        /// </summary>
        public static bool IgnoresDefenses(LSO_DamageSource source)
        {
            switch (source)
            {
                // 상어왕 사냥터. 미리 경고된 영역이라 피할 시간을 준 대신,
                // 맞으면 특성으로는 버틸 수 없다.
                case LSO_DamageSource.SharkKingZone:
                    return true;

                default:
                    return false;
            }
        }
    }
}
