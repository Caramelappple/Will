namespace _Scripts.LSO.HealthSystem
{
    /// <summary>
    /// 피해 수정자가 도는 차례. **작을수록 먼저 돈다.**
    ///
    /// ── 왜 이름을 붙였나 ──────────────────────────────────────
    /// 예전에는 각 특성이 -1000, 0, 1000 같은 숫자를 직접 적고,
    /// 그 옆에 "무효화 계열은 먼저 처리한다" 같은 주석을 각자 달아뒀다.
    /// 여섯 곳에 비슷한 설명이 흩어져 있었고, 전체 순서를 보려면
    /// 여섯 파일을 다 열어야 했다.
    ///
    /// 새 특성을 만드는 사람이 -500을 적으면 그게 어디 끼는지 알 방법이 없었다.
    /// 이제 여기 있는 이름 중에 고르면 된다.
    /// ─────────────────────────────────────────────────────────
    ///
    /// 차례가 왜 중요한가 — 증폭이 무효화보다 먼저 돌아야 한다.
    /// 순서가 뒤집히면 회피로 0이 된 피해에 +2가 더해져서, 피했는데 2를 맞는다.
    /// 무효화가 옹골참보다 먼저 돌아야, 어차피 0이 될 피해에
    /// 한 번뿐인 옹골참이 헛되이 소진되지 않는다.
    /// </summary>
    public static class LSO_DamagePriority
    {
        /// <summary>
        /// 피해를 **더하는** 것. 가장 먼저 돈다.
        ///
        /// 무효화보다 앞에 둬야 뒤따르는 감쇄가 늘어난 값을 기준으로 계산한다.
        /// 쓰는 곳: DLJ_SharkKingPreyMark(포식 표식 +2),
        /// DLJ_FoxKingInvestment(투자로 쌓인 공격력 보너스).
        /// </summary>
        public const int Amplify = -2000;

        /// <summary>
        /// 피해를 **0으로 만드는** 것. 회피 · 저주 면역.
        ///
        /// 여기서 0이 되면 뒤의 한 번뿐인 특성(옹골참)이 헛되이 소진되지 않는다.
        /// </summary>
        public const int Nullify = -1000;

        /// <summary>
        /// 보통 감쇄. 특별히 앞뒤를 다툴 이유가 없으면 이걸 쓴다.
        ///
        /// 허약이 여기 있는 것은 의도다 — 무효화 계열보다 앞에 두면
        /// 그 특성들이 헛되이 발동한 것으로 기록된다.
        /// </summary>
        public const int Normal = 0;

        /// <summary>
        /// 마지막 보루. 앞의 계산이 다 끝난 값을 받는다. 옹골참.
        ///
        /// "이 피해로 죽는가"를 판정하려면 최종 값이어야 하므로 맨 뒤여야 한다.
        /// </summary>
        public const int LastStand = 1000;
    }
}
